const PDFDocument = require('pdfkit');

/**
 * Generate A4-formatted PDF for Advance ML Symptom Prediction Report
 * @param {Object} data - { symptoms, topMatches, patientName, disclaimer, createdAt }
 * @param {WritableStream} outputStream 
 */
function buildAdvanceReportPDF(data, outputStream) {
  const doc = new PDFDocument({ margin: 40, size: 'A4' });
  doc.pipe(outputStream);

  const patientName = data.patientName || 'Patient';
  const reportDate = data.createdAt ? new Date(data.createdAt).toLocaleString() : new Date().toLocaleString();
  const symptoms = data.symptoms || [];
  const topMatches = data.topMatches || [];
  const disclaimer = data.disclaimer || 'This report is generated by a Machine Learning symptom classification model. It is intended strictly for preliminary AI screening, NOT as a medical diagnosis.';

  // 1. Primary Header Banner
  doc.rect(40, 40, 515, 65).fill('#0f172a');
  doc.fillColor('#38bdf8').fontSize(18).font('Helvetica-Bold').text('Smart Health Prediction', 55, 52);
  doc.fillColor('#34d399').fontSize(12).font('Helvetica-Bold').text('Advance ML Disease Classification Report', 55, 75);
  doc.fillColor('#94a3b8').fontSize(9).font('Helvetica').text('AI Biometric & Clinical Screening Platform', 350, 75, { align: 'right' });

  let y = 120;

  // 2. Patient & Report Metadata Box
  doc.rect(40, y, 515, 50).fillAndStroke('#f8fafc', '#cbd5e1');
  doc.fillColor('#1e293b').fontSize(10).font('Helvetica-Bold').text('Patient Name:', 55, y + 12);
  doc.fillColor('#0f172a').fontSize(10).font('Helvetica').text(patientName, 130, y + 12);

  doc.fillColor('#1e293b').fontSize(10).font('Helvetica-Bold').text('Date & Time:', 55, y + 30);
  doc.fillColor('#0f172a').fontSize(10).font('Helvetica').text(reportDate, 130, y + 30);

  doc.fillColor('#1e293b').fontSize(10).font('Helvetica-Bold').text('Report Ref ID:', 340, y + 12);
  doc.fillColor('#0284c7').fontSize(9).font('Helvetica-Bold').text(`ADV-${Date.now().toString().substring(5)}`, 425, y + 12);

  doc.fillColor('#1e293b').fontSize(10).font('Helvetica-Bold').text('Analysis Type:', 340, y + 30);
  doc.fillColor('#059669').fontSize(9).font('Helvetica-Bold').text('Multi-Class Random Forest ML', 425, y + 30);

  y += 65;

  // 3. Selected Symptoms Section
  doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text(`Selected Symptoms (${symptoms.length})`, 40, y);
  y += 18;

  const formattedSymptoms = symptoms.map(s => s.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase())).join(', ');
  doc.rect(40, y, 515, 40).fillAndStroke('#f1f5f9', '#e2e8f0');
  doc.fillColor('#334155').fontSize(9.5).font('Helvetica').text(formattedSymptoms || 'None specified', 50, y + 8, { width: 495 });

  y += 50;

  // 4. Ranked ML Disease Predictions
  doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('Ranked ML Disease Predictions', 40, y);
  y += 20;

  topMatches.forEach((match, idx) => {
    const isTop = idx === 0;
    const boxHeight = isTop ? 65 : 50;

    doc.rect(40, y, 515, boxHeight).fillAndStroke(isTop ? '#ecfdf5' : '#f8fafc', isTop ? '#059669' : '#cbd5e1');

    doc.fillColor(isTop ? '#047857' : '#334155').fontSize(11).font('Helvetica-Bold').text(`#${idx + 1}  ${match.disease}`, 55, y + 10);
    doc.fillColor(isTop ? '#047857' : '#0284c7').fontSize(11).font('Helvetica-Bold').text(`${match.confidence}% Confidence`, 430, y + 10, { align: 'right' });

    // Precautions
    if (match.precautions && match.precautions.length > 0) {
      const precText = 'Recommended Precautions: ' + match.precautions.join(' • ');
      doc.fillColor('#475569').fontSize(8.5).font('Helvetica').text(precText, 55, y + 30, { width: 480 });
    }

    y += boxHeight + 10;
  });

  y += 10;

  // 5. Model Architecture Specifications Footer Box
  doc.rect(40, y, 515, 45).fillAndStroke('#f0f9ff', '#bae6fd');
  doc.fillColor('#0369a1').fontSize(9).font('Helvetica-Bold').text('Machine Learning Model Architecture Specifications', 55, y + 8);
  doc.fillColor('#0c4a6e').fontSize(8.5).font('Helvetica').text(
    'Algorithm: Random Forest Classifier (100 Decision Trees) | Feature Space: 131 Unified Binary Symptoms\n' +
    'Target Classes: 41 Disease Categories | Training Records: 9,882 merged Kaggle dataset samples (100% Validation Accuracy)',
    55, y + 22
  );

  y += 55;

  // 6. Medical Disclaimer Box
  doc.rect(40, y, 515, 45).fillAndStroke('#fffbeb', '#fcd34d');
  doc.fillColor('#b45309').fontSize(9).font('Helvetica-Bold').text('Important Medical Disclaimer', 55, y + 8);
  doc.fillColor('#78350f').fontSize(8).font('Helvetica').text(disclaimer, 55, y + 22, { width: 485 });

  // Footer page timestamp
  doc.fillColor('#94a3b8').fontSize(8).font('Helvetica').text(`Smart Health Prediction Platform — Generated on ${new Date().toISOString()}`, 40, 800, { align: 'center' });

  doc.end();
}

module.exports = {
  buildAdvanceReportPDF
};
