const express = require('express');
const router = express.Router();
const advanceMlService = require('../services/advanceMlService');
const advancePdfService = require('../services/advancePdfService');
const db = require('../db');

// GET /api/advance-predict/symptoms - Get symptom checklist and category metadata
router.get('/symptoms', (req, res) => {
  try {
    const metadata = advanceMlService.getMetadata();
    if (!metadata) {
      return res.status(500).json({ message: 'Advance ML dataset metadata not initialized' });
    }
    res.json({
      status: 'success',
      symptoms: metadata.symptoms,
      symptomDetails: metadata.symptomDetails,
      categorizedSymptoms: metadata.categorizedSymptoms,
      diseaseCount: metadata.diseaseCount,
      symptomCount: metadata.symptomCount,
      datasetSamples: metadata.datasetSamples,
      bestModelName: metadata.bestModelName || 'Random Forest Classifier',
      bestValAccuracy: metadata.bestValAccuracy || 100.0,
      modelComparison: metadata.modelComparison || {}
    });
  } catch (err) {
    console.error('Error fetching symptom checklist metadata:', err);
    res.status(500).json({ message: 'Failed to retrieve symptom checklist metadata' });
  }
});

// POST /api/advance-predict - Run ML disease prediction on selected symptoms & log statistics
router.post('/', async (req, res) => {
  try {
    const { symptoms } = req.body;
    if (!Array.isArray(symptoms)) {
      return res.status(400).json({ message: 'Symptoms must be provided as an array of symptom IDs' });
    }

    const metadata = advanceMlService.getMetadata() || {};
    const predictionResult = await advanceMlService.predict(symptoms);
    
    predictionResult.modelInfo = {
      name: metadata.bestModelName || 'Random Forest Classifier',
      accuracy: (metadata.bestValAccuracy || 100.0) + '%',
      comparison: metadata.modelComparison || {}
    };

    // Log prediction record for admin read-only analytics
    try {
      db.insert('advance_reports', {
        symptoms,
        symptomCount: symptoms.length,
        topDisease: predictionResult.topMatches?.[0]?.disease || 'Unknown',
        confidence: predictionResult.topMatches?.[0]?.confidence || 0,
        topMatches: predictionResult.topMatches || [],
        createdAt: new Date().toISOString()
      });
    } catch (logErr) {
      console.warn('Failed to log advance prediction record:', logErr);
    }

    res.json(predictionResult);
  } catch (err) {
    console.error('Error processing advance ML disease prediction:', err);
    res.status(500).json({ message: 'Error processing ML disease prediction: ' + err.message });
  }
});

// POST /api/advance-predict/pdf - Stream Standalone PDF Report
router.post('/pdf', (req, res) => {
  try {
    const { symptoms, topMatches, patientName, disclaimer } = req.body;

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', 'attachment; filename=Advance_ML_Disease_Report.pdf');

    advancePdfService.buildAdvanceReportPDF({
      symptoms: symptoms || [],
      topMatches: topMatches || [],
      patientName: patientName || 'Patient',
      disclaimer: disclaimer || 'This report is generated by a Machine Learning symptom classification model.',
      createdAt: new Date().toISOString()
    }, res);
  } catch (err) {
    console.error('Advance PDF generation error:', err);
    if (!res.headersSent) {
      res.status(500).json({ message: 'Failed to generate Advance ML PDF report' });
    }
  }
});

module.exports = router;
