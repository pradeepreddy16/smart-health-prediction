import sys
import os
import json
import warnings
warnings.filterwarnings("ignore")

import pandas as pd
import numpy as np
import joblib

OUTPUT_DIR = r"c:\Users\Thrishi\Desktop\shp\backend\data"
MODEL_PATH = os.path.join(OUTPUT_DIR, "advance_model.joblib")
METADATA_PATH = os.path.join(OUTPUT_DIR, "advance_metadata.json")

def main():
    if len(sys.argv) < 2:
        print(json.dumps({"error": "No symptoms provided"}))
        sys.exit(1)

    try:
        input_symptoms = json.loads(sys.argv[1])
    except Exception as e:
        print(json.dumps({"error": f"Invalid JSON input: {str(e)}"}))
        sys.exit(1)

    if not os.path.exists(MODEL_PATH) or not os.path.exists(METADATA_PATH):
        print(json.dumps({"error": "Trained model or metadata file missing"}))
        sys.exit(1)

    with open(METADATA_PATH, 'r') as f:
        metadata = json.load(f)

    model = joblib.load(MODEL_PATH)

    symptom_list = metadata["symptoms"]
    classes = list(model.classes_)
    precautions_map = metadata.get("precautions", {})

    input_set = set([s.strip().lower() for s in input_symptoms])
    
    # Construct DataFrame with feature names to prevent scikit-learn warnings
    sample_dict = {s: [1 if s in input_set else 0] for s in symptom_list}
    df_sample = pd.DataFrame(sample_dict)

    probabilities = model.predict_proba(df_sample)[0]
    
    # Sort indices by probability descending
    top_indices = np.argsort(probabilities)[::-1]

    top_matches = []
    for idx in top_indices[:3]:
        prob = float(probabilities[idx])
        disease_name = classes[idx]
        precs = precautions_map.get(disease_name, ["Consult a qualified medical specialist for clinical evaluation."])
        
        top_matches.append({
            "disease": disease_name,
            "confidence": round(prob * 100, 1),
            "precautions": precs
        })

    if len(input_set) == 0:
        top_matches = [{
            "disease": "No Symptoms Selected",
            "confidence": 0.0,
            "precautions": ["Please select at least one symptom from the checklist."]
        }]

    result = {
        "status": "success",
        "topMatches": top_matches,
        "selectedCount": len(input_set),
        "disclaimer": "This report is generated by a Machine Learning symptom classification model trained on combined clinical dataset records. It is intended strictly for preliminary AI screening and informational reference, NOT as a medical diagnosis. Always consult a certified physician for medical advice."
    }

    print(json.dumps(result))

if __name__ == '__main__':
    main()
